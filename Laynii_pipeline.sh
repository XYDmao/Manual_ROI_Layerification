#!/bin/bash

# list of subject IDs
subjects=("S03")

# base path
base_dir=/data/xd25/Laminar_hallucinations/Subject_data

# directory to return to
return_dir=/data/xd25/Laminar_hallucinations/Analysis_code/Phase3_ROI_creation/laynii

for subj in "${subjects[@]}"
do
    echo "========================================"
    echo "Processing subject: ${subj}"
    echo "========================================"

    subj_dir=${base_dir}/${subj}/${subj}_for_LayNii

    if [ ! -d "${subj_dir}" ]; then
        echo "ERROR: Directory does not exist:"
        echo "${subj_dir}"
        echo "Skipping ${subj}..."
        continue
    fi

    cd "${subj_dir}" || continue

    # loop through mask0.nii, mask1.nii, mask2.nii, ...
    for rim in activation_clusters_upsampled_mask[0-9]*.nii
    do
        # if no matching files exist
        if [ ! -f "${rim}" ]; then
            continue
        fi

        # only process original mask files
        # avoid processing files generated by LAYNII
        if [[ ! "${rim}" =~ ^activation_clusters_upsampled_mask[0-9]+\.nii$ ]]; then
            continue
        fi

        stem="${rim%.nii}"
        midgm="${stem}_midGM_equivol.nii"

        echo ""
        echo "Processing: ${rim}"

        echo "Running LN2_LAYERS..."

        LN2_LAYERS \
            -rim "${rim}" \
            -incl_borders \
            -equivol \
            -nr_layers 3  # modify the number of layers here

        if [ $? -ne 0 ]; then
            echo "ERROR: LN2_LAYERS failed for ${rim}"
            continue
        fi

        echo "Running LN2_COLUMNS..."

        LN2_COLUMNS \
            -rim "${rim}" \
            -midgm "${midgm}" \
            -incl_borders \
            -nr_columns 7   # modify the number of columns here

        if [ $? -ne 0 ]; then
            echo "ERROR: LN2_COLUMNS failed for ${rim}"
            continue
        fi

        echo "Finished: ${rim}"

    done

    echo ""
    echo "Finished ${subj}"
    echo ""

done

echo "========================================"
echo "All subjects processed!"
echo "========================================"

cd "${return_dir}"
echo "Changed directory back to: ${return_dir}"
